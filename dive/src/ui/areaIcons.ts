/** 影のアイコンの SVG。色は呼び出し側の CSS（`.ico { --ico-bg }`）で決める。 */
export function areaIconSvg(id: string): string {
  const ic = AREA_ICONS[id];
  if (!ic) return '';
  const st = (list: Stroke[] | undefined, color: string) => (list ?? []).map((x) => `<path d="${x.d}" fill="none" stroke="${color}" stroke-width="${x.w}" stroke-linecap="round" stroke-linejoin="round"/>`).join('');
  const DARK = 'var(--ico-ink)', BG = 'var(--ico-bg)';
  return `<svg viewBox="0 0 24 24" aria-hidden="true">${ic.f.map((d) => `<path d="${d}" fill="${DARK}"/>`).join('')}${st(ic.s, DARK)}${(ic.cut ?? []).map((d) => `<path d="${d}" fill="${BG}"/>`).join('')}${st(ic.cs, BG)}</svg>`;
}
