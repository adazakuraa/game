import * as THREE from 'three';
import sandUrl from '../assets/tex/sand.webp';
import polypUrl from '../assets/tex/polyp.webp';
import brainUrl from '../assets/tex/brain.webp';
import sandA from '../assets/tex/pbr_sand_a.jpg';
import sandN from '../assets/tex/pbr_sand_n.jpg';
import rubA from '../assets/tex/pbr_rubble_a.jpg';
import rubN from '../assets/tex/pbr_rubble_n.jpg';
import reefA from '../assets/tex/pbr_reef_a.jpg';
import reefN from '../assets/tex/pbr_reef_n.jpg';
import rockA from '../assets/tex/pbr_rock_a.jpg';
import rockN from '../assets/tex/pbr_rock_n.jpg';
import rustA from '../assets/tex/pbr_rust_a.jpg';
import rustN from '../assets/tex/pbr_rust_n.jpg';

/** Baked tileable detail maps (RGB tangent normal, A albedo detail). Generated by scripts/gen_textures.py. */
const loader = new THREE.TextureLoader();
function load(url: string): THREE.Texture {
  const t = loader.load(url);
  t.wrapS = t.wrapT = THREE.RepeatWrapping;
  t.colorSpace = THREE.NoColorSpace;
  t.anisotropy = 8;
  t.generateMipmaps = true;
  t.minFilter = THREE.LinearMipmapLinearFilter;
  return t;
}
let cache: Record<string, THREE.Texture> | null = null;
export function baked() {
  if (!cache) cache = { sand: load(sandUrl), polyp: load(polypUrl), brain: load(brainUrl) };
  return cache as { sand: THREE.Texture; polyp: THREE.Texture; brain: THREE.Texture };
}

export type PbrPair = { a: THREE.Texture; n: THREE.Texture };
let pcache: Record<string, PbrPair> | null = null;
/** Photo-sourced CC0 PBR pairs (Poly Haven), prepared by scripts/prep_pbr.py. */
export function pbr() {
  if (!pcache)
    pcache = {
      sand: { a: load(sandA), n: load(sandN) },
      rubble: { a: load(rubA), n: load(rubN) },
      reef: { a: load(reefA), n: load(reefN) },
      rock: { a: load(rockA), n: load(rockN) },
      rust: { a: load(rustA), n: load(rustN) },
    };
  return pcache as Record<'sand' | 'rubble' | 'reef' | 'rock' | 'rust', PbrPair>;
}
